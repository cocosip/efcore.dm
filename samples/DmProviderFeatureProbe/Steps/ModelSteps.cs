    private static async Task OwnedSameTableAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.Add(new Customer
        {
            Name = "owned",
            Address = new Address { Street = "1 main street", City = "hangzhou" },
            Balance = new Money { Amount = 1m, Currency = "CNY" },
        });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        var read = await context.Customers.SingleAsync(cancellationToken);
        Assert.Equal("1 main street", read.Address.Street, "owned street round-trips");
