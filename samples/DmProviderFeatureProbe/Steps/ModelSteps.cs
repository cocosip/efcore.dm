    private static async Task IdentityKeysAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.AddRange(
            new KeyShape { GuidKey = Guid.NewGuid(), StringKey = "first" },
            new KeyShape { GuidKey = Guid.NewGuid(), StringKey = "second" },
            new LongKeyRow { Name = "long one" },
            new LongKeyRow { Name = "long two" });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        var rows = await context.KeyShapes.OrderBy(row => row.Id).ToListAsync(cancellationToken);
        Assert.Equal(2, rows.Count, "two rows");
        Assert.True(rows[1].Id > rows[0].Id, "the int key is generated and increasing");

        var longIds = await context.LongKeyRows.Select(row => row.Id).ToListAsync(cancellationToken);
        Assert.Equal(2, longIds.Count, "two long-key rows");
        Assert.True(longIds.All(id => id > 0), "the long key is generated");
        Assert.Equal(2, longIds.Distinct().Count(), "the long keys are distinct");
    }

    private static async Task OtherKeysAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        var guid = Guid.NewGuid();

        context.Add(new KeyShape { GuidKey = guid, StringKey = "string-key" });
        context.Add(new CompositeKeyRow { PartA = 7, PartB = "part-b", Payload = "payload" });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        Assert.Equal(1, await context.KeyShapes.CountAsync(row => row.GuidKey == guid, cancellationToken),
            "Guid key round trip");
        Assert.Equal(1, await context.KeyShapes.CountAsync(row => row.StringKey == "string-key", cancellationToken),
            "string key round trip");
        Assert.Equal("payload", (await context.CompositeKeys.SingleAsync(
            row => row.PartA == 7 && row.PartB == "part-b", cancellationToken)).Payload,
            "composite key lookup");
    }

    private static async Task HiLoAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.AddRange(new HiLoRow { Name = "one" }, new HiLoRow { Name = "two" });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        await using (var second = new FeatureContext(context.ConnectionString))
        {
            second.AddRange(new HiLoRow { Name = "three" }, new HiLoRow { Name = "four" });
            await second.SaveChangesAsync(cancellationToken);
        }

        var ids = await context.HiLoRows.Select(row => row.Id).ToListAsync(cancellationToken);
        Assert.Equal(4, ids.Count, "four rows");
        Assert.Equal(4, ids.Distinct().Count(), "hi-lo hands out distinct keys");
    }

    private static async Task IndexesAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.Add(new KeyShape { GuidKey = Guid.NewGuid(), StringKey = "unique" });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        context.Add(new KeyShape { GuidKey = Guid.NewGuid(), StringKey = "unique" });
        await Assert.ThrowsAsync<DbUpdateException>(
            () => context.SaveChangesAsync(cancellationToken),
            "a duplicate unique key");
        context.ChangeTracker.Clear();

        var indexes = context.Model.FindEntityType(typeof(KeyShape))!.GetIndexes().ToArray();
        Assert.True(indexes.Any(index => index.IsUnique
                                         && index.Properties.Count == 1
                                         && index.Properties[0].Name == nameof(KeyShape.StringKey)),
            "the single-column unique index is in the model");
        Assert.True(indexes.Any(index => index.Properties.Count == 2),
            "the composite index is in the model");
        Assert.True(indexes.Any(index => index.Properties.Count == 1
                                         && index.Properties[0].Name == nameof(KeyShape.GuidKey)
                                         && !index.IsUnique),
            "the plain index is in the model");
    }

