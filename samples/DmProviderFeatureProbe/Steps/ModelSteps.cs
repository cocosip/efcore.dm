    }

    private static async Task TphAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.AddRange(
            new Dog { Name = "dog", BarkVolume = 3 },
            new Cat { Name = "cat", Lives = 9 });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        Assert.Equal(2, await context.Animals.CountAsync(cancellationToken), "both rows are animals");
        Assert.Equal(1, await context.Animals.OfType<Dog>().CountAsync(cancellationToken), "OfType is a dog");
        var kinds = await context.Animals
            .Select(animal => EF.Property<string>(animal, "kind"))
            .OrderBy(kind => kind)
            .ToListAsync(cancellationToken);
        Assert.Equal("cat,dog", string.Join(",", kinds), "the discriminator is stored");
    }

    private static async Task TptAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.AddRange(
            new Car { Name = "car", Doors = 4 },
            new Truck { Name = "truck", Payload = 12.5m });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        Assert.Equal(2, await context.Vehicles.CountAsync(cancellationToken), "both rows are vehicles");
