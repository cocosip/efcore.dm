        var owned = context.Model.FindEntityType(typeof(Customer))!
            .FindNavigation(nameof(Customer.Address))!.TargetEntityType;
        Assert.Equal("DM_FEATURE_CUSTOMERS", owned.GetTableName(), "the owned type shares the owner's table");
    }

