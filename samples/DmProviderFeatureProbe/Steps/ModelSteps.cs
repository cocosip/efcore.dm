    private static async Task ShadowAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        var parent = new Shadowed { Name = "shadowed" };
        context.Add(parent);
        context.Entry(parent).Property("ShadowNumber").CurrentValue = 42;
        context.Entry(parent).Property(nameof(Shadowed.Note)).CurrentValue = "private field";
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        var read = await context.Shadowed.SingleAsync(cancellationToken);
        Assert.Equal(42, (int)context.Entry(read).Property("ShadowNumber").CurrentValue!,
            "the shadow property round-trips");
        Assert.Equal("private field", read.Note, "the private backing field round-trips");

        var child = new ShadowChild { Name = "child" };
        context.Add(child);
        context.Entry(child).Property("ParentId").CurrentValue = read.Id;
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        Assert.Equal(1, await context.ShadowChildren.CountAsync(
            row => EF.Property<int>(row, "ParentId") == read.Id, cancellationToken),
            "the shadow foreign key round-trips");
    }

    private static async Task ConcurrencyAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.Add(new Versioned { Name = "version one" });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        var loaded = await context.Versioned.SingleAsync(cancellationToken);

        // The token only detects a lost update when the other writer advances it, which is what a
        // version column configured as a concurrency token requires of the application.
        await using (var other = new FeatureContext(context.ConnectionString))
        {
            var otherRow = await other.Versioned.SingleAsync(cancellationToken);
            otherRow.Name = "changed elsewhere";
            otherRow.Version++;
            await other.SaveChangesAsync(cancellationToken);
        }

        loaded.Name = "version two";
        await Assert.ThrowsAsync<DbUpdateConcurrencyException>(
            () => context.SaveChangesAsync(cancellationToken),
            "a stale concurrency token");
    }

