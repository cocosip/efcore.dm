    private static async Task ConventionsAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        var entity = context.Model.FindEntityType(typeof(AnnotatedRecord))!;
        Assert.NotNull(entity, "the annotated entity is in the model");
        Assert.Equal("DM_FEATURE_ANNOTATED", entity.GetTableName(), "table from [Table]");

        var caption = entity.FindProperty(nameof(AnnotatedRecord.Caption))!;
        Assert.Equal("caption", caption.GetColumnName(), "column from [Column]");
        Assert.Equal(40, caption.GetMaxLength(), "length from [MaxLength]");
        Assert.True(!caption.IsNullable, "required from [Required]");
        Assert.Equal("DECIMAL(12,3)", entity.FindProperty(nameof(AnnotatedRecord.Amount))!.GetColumnType(),
            "type from [Column(TypeName)]");

        context.Add(new AnnotatedRecord { Caption = "annotated", Amount = 12.345m });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        var read = await context.Annotated.SingleAsync(cancellationToken);
        Assert.Equal("annotated", read.Caption, "caption round trip");
        Assert.Equal(12.345m, read.Amount, "amount round trip");
    }

