    private static async Task ConverterAsync(FeatureContext context, CancellationToken cancellationToken)
    {
        context.Add(new Customer
        {
            Name = "converted",
            Address = new Address { Street = "4 low street", City = "wuhan" },
            Balance = new Money { Amount = 2m, Currency = "CNY" },
            Tier = Tier.Gold,
            TierText = Tier.Silver,
        });
        await context.SaveChangesAsync(cancellationToken);
        context.ChangeTracker.Clear();

        Assert.Equal(1, await context.Customers.CountAsync(
            customer => customer.Tier == Tier.Gold, cancellationToken),
            "the integer-backed enum is filtered on the server");
        Assert.Equal(1, await context.Customers.CountAsync(
            customer => customer.TierText == Tier.Silver, cancellationToken),
            "the converted enum is filtered on the server");

        var property = context.Model.FindEntityType(typeof(Customer))!.FindProperty(nameof(Customer.TierText))!;
        Assert.Equal(typeof(string), property.GetProviderClrType(), "the converter's provider type is string");
        Assert.Equal(Tier.Silver, (await context.Customers.SingleAsync(cancellationToken)).TierText,
            "the converted value round-trips");
    }

